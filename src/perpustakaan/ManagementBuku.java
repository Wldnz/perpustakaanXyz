    private Boolean canContinueToDoing(HashMap<String,String> data){
        canContinue = true;
        data.forEach((k, v) -> {
            if(v.isEmpty() && !k.contains("isbn")){
                if(k.equals("image_url")){
                    image_url.setText("https://cdn2.hubspot.net/hubfs/242200/shutterstock_774749455.jpg");
                }else{
                    canContinue = false;
                }
            }
        });
        return canContinue;
    }
    
